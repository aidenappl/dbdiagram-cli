#!/usr/bin/env bash
# Regenerate THIRD_PARTY_NOTICES from the module graph of the shipped binary
# (every release target, CGO disabled — test-only modules are excluded).
# For each module: path, version, every LICENSE/LICENCE/COPYING/NOTICE/PATENTS
# file verbatim, and — for MPL-2.0 modules — where the unmodified Source Code
# Form is available (MPL-2.0 §3.2). Run after any dependency change:
#   scripts/third_party_notices.sh            # rewrites THIRD_PARTY_NOTICES
#   scripts/third_party_notices.sh OUTFILE    # writes elsewhere (release.sh checks staleness)
set -euo pipefail
out="${1:-THIRD_PARTY_NOTICES}"
case "$out" in /*) ;; *) out="$PWD/$out" ;; esac
cd "$(dirname "$0")/.."
mods=$(for t in darwin/amd64 darwin/arm64 linux/amd64 linux/arm64 windows/amd64 windows/arm64; do
	GOOS="${t%/*}" GOARCH="${t#*/}" CGO_ENABLED=0 go list -deps \
		-f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}}{{end}}{{end}}' .
done | sort -u)
{
	echo "THIRD-PARTY SOFTWARE NOTICES AND INFORMATION"
	echo
	echo "dbdiagram-cli (Apache-2.0, see LICENSE and NOTICE) is distributed with the"
	echo "following third-party Go modules, compiled into the binary. Each module's"
	echo "license and notice files are reproduced below, unmodified."
	echo "Generated by scripts/third_party_notices.sh — do not edit by hand."
	echo
	echo "Modules:"
	echo "  - Go standard library $(go env GOVERSION) (BSD-3-Clause)"
	while read -r m v; do echo "  - $m $v"; done <<< "$mods"
	section() {
		echo
		echo "================================================================================"
		echo "$1"
		echo "================================================================================"
	}
	goroot=$(go env GOROOT)
	golicense=""
	for f in "$goroot/LICENSE" "$goroot/../LICENSE"; do
		if [ -f "$f" ]; then golicense="$f"; break; fi
	done
	if [ -z "$golicense" ]; then echo "error: Go's LICENSE not found under $goroot" >&2; exit 1; fi
	section "Go standard library $(go env GOVERSION) — LICENSE"
	cat "$golicense"
	if [ -f "$goroot/PATENTS" ]; then
		section "Go standard library $(go env GOVERSION) — PATENTS"
		cat "$goroot/PATENTS"
	fi
	while read -r m v; do
		dir=$(go list -m -f '{{.Dir}}' "$m")
		found=0
		for f in $(ls "$dir" | grep -iE '^(licen[cs]e|copying|notice|patents)([.-][a-z0-9_.-]*)?$' | grep -viE '\.go$' | sort); do
			section "$m $v — $f"
			cat "$dir/$f"
			found=1
		done
		if [ "$found" = 0 ]; then
			echo "error: no license file found for $m $v" >&2
			exit 1
		fi
		if grep -qs "Mozilla Public License" "$dir"/LICENSE*; then
			section "$m $v — MPL-2.0 Source Code Form"
			echo "This module is licensed under the Mozilla Public License 2.0 and is"
			echo "included unmodified. Its Source Code Form is available at:"
			echo "  https://proxy.golang.org/$m/@v/$v.zip"
			echo "  https://pkg.go.dev/$m@$v"
		fi
	done <<< "$mods"
} > "$out"
echo "wrote $out ($(wc -l < "$out") lines, $(wc -l <<< "$mods") modules)"
